'use strict';
const assert = require('node:assert/strict');
const tabsApi = require('../pipeline_tabs.js');
const values = new Map();
const storage = { getItem: key => values.get(key), setItem: (key, value) => values.set(key, value) };
const tabs = tabsApi.create({ storage, key: 'one' });
let notices = 0;
const unsubscribe = tabs.subscribe(() => notices++);
tabs.add({id:'a',name:'Alpha'}); tabs.add({id:'b',name:'Beta'}); tabs.add({id:'c',name:'Gamma'},false);
assert.deepEqual(tabs.items.map(x=>x.id), ['a','b','c']); assert.equal(tabs.activeId,'b');
const previous = tabs.getSnapshot();
tabs.get('a').name = 'must not mutate canonical data';
assert.equal(tabs.get('a').name, 'Alpha');
assert.throws(()=>{previous.items[0].name='bad'},TypeError);
tabs.activate('a'); tabs.move('c','a'); tabs.remove('a');
assert.deepEqual(tabs.items.map(x=>x.id),['c','b']); assert.equal(tabs.activeId,'b');
assert.equal(previous.activeId,'b'); assert.equal(previous.items.length,3);
assert.equal(tabsApi.create({storage,key:'one'}).activeId,'b');
assert.deepEqual(tabsApi.create({storage,key:'two'}).items,[]);
assert.equal(tabsApi.create({storage,key:'two'}).hasSavedCatalog,false);
values.set('closed',JSON.stringify({version:1,items:[],activeId:''}));
assert.equal(tabsApi.create({storage,key:'closed'}).hasSavedCatalog,true,'an intentionally empty catalog is authoritative');
values.set('corrupt','not json');
assert.equal(tabsApi.create({storage,key:'corrupt'}).hasSavedCatalog,false);
assert.equal(tabs.add({id:'',name:'bad'}),null); assert.equal(tabs.activate('unknown'),false);
const n = notices; unsubscribe(); tabs.add({id:'d',name:'Delta'}); assert.equal(notices,n);
const broken = tabsApi.create({storage:{getItem(){throw Error('locked')},setItem(){throw Error('full')}}});
broken.add({id:'valid',name:'survives storage failure'}); assert.equal(broken.items.length,1);
let mounted=0,updated=0,disposed=0;
const bridge=tabsApi.create({storage,key:'bridge',mountView:(host,catalog,handlers)=>{
  assert.equal(catalog,bridge);mounted++;return {update:()=>updated++,dispose:()=>disposed++};
}});
const host={hidden:true}; bridge.render(host,{}); bridge.render(host,{});
assert.equal(host.hidden,false);assert.equal(mounted,1);assert.equal(updated,1);
bridge.destroy();assert.equal(disposed,1);
console.log('pipeline tabs ok (immutable snapshots, subscription cleanup, persistence, window isolation, view ownership)');
